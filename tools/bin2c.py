#!/usr/bin/env python3
"""bin2c.py IN.bin OUT.h NAME: a const uint8_t array of the file."""
import sys
d = open(sys.argv[1], 'rb').read()
name = sys.argv[3]
lines = ['// generated by tools/bin2c.py from %s: do not edit' % sys.argv[1].split('/')[-1],
         '#pragma once', '#include <stdint.h>', 'static const uint8_t %s[%d] = {' % (name, len(d))]
for i in range(0, len(d), 16):
    lines.append('  ' + ' '.join('0x%02X,' % b for b in d[i:i + 16]))
lines.append('};')
open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
