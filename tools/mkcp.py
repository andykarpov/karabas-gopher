#!/usr/bin/env python3
"""Tables for src/gopher/cp.c: CP1251 / KOI8-R upper halves -> CP866, and the Unicode code points of
CP866 0x80..0xFF (sorted, for UTF-8 -> CP866) plus a few look-alike fallbacks.
  mkcp.py OUT.h"""
import sys

# characters CP866 lacks: the nearest it has
FALL = {'—': '-', '–': '-', '‘': "'", '’': "'", '‚': "'", '“': '"',
        '”': '"', '„': '"', '«': '"', '»': '"', '…': '.', '•': '\xf9',
        'і': 'i', 'І': 'I', '™': 'T', '©': 'c', '®': 'R', '№': '\xfc',
        'ґ': '\xa3', 'Ґ': '\x83', ' ': ' '}
def table(codec):
    out = []
    for b in range(128, 256):
        ch = bytes([b]).decode(codec, 'replace')
        try:
            out.append(ch.encode('cp866')[0])
        except UnicodeEncodeError:
            v = FALL.get(ch)
            out.append(ord(v) if v and len(v) == 1 else ord('?'))
    return out

lines = ['// generated by tools/mkcp.py: do not edit', '#pragma once', '#include <stdint.h>', '']
for name, codec in (('cp1251', 'cp1251'), ('koi8', 'koi8_r')):
    t = table(codec)
    lines.append('static const uint8_t %s_866[128] = {' % name)
    for i in range(0, 128, 16):
        lines.append('  ' + ' '.join('0x%02X,' % v for v in t[i:i + 16]))
    lines.append('};')
pairs = sorted((ord(bytes([b]).decode('cp866')), b) for b in range(128, 256))
for ch, v in FALL.items():
    if not any(u == ord(ch) for u, _ in pairs) and len(v) == 1:
        pairs.append((ord(ch), ord(v)))
pairs.sort()
lines.append('// Unicode -> CP866 for code points >= 0x80, sorted by code point')
lines.append('static const uint16_t uni_cp[%d] = {' % len(pairs))
for i in range(0, len(pairs), 12):
    lines.append('  ' + ' '.join('0x%04X,' % u for u, _ in pairs[i:i + 12]))
lines.append('};')
lines.append('static const uint8_t uni_866[%d] = {' % len(pairs))
for i in range(0, len(pairs), 16):
    lines.append('  ' + ' '.join('0x%02X,' % b for _, b in pairs[i:i + 16]))
lines.append('};')
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
